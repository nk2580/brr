import { mkdir } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { installChatExperienceFixture } from './fixtures/chat-experience'

const evidence = 'projects/desktop-agent/evidence/conversation-first'

test.beforeEach(async ({ page }) => {
  await mkdir(evidence, { recursive: true })
  await installChatExperienceFixture(page)
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'New conversation' })).toBeVisible()
  await expect(page.getByRole('combobox', { name: 'Model' })).toBeEnabled()
})

test('keeps independent drafts and settings through navigation and reload at both target sizes', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 860 })
  await page.getByRole('button', { name: 'New conversation' }).click()
  const message = page.getByRole('textbox', { name: 'Message' })
  await message.fill('Keep this local planning note')
  await page.getByRole('combobox', { name: 'Model' }).selectOption('astra')
  await page.getByRole('button', { name: 'Plan mode' }).click()
  await page.getByRole('button', { name: 'Chat options' }).click()
  await page.getByRole('combobox', { name: 'Reasoning effort' }).selectOption('medium')
  await expect.poll(() => page.evaluate(() => {
    const state = (window as any).__chatExperience.inspect()
    return state.drafts.some((draft: any) => draft.document?.text === 'Keep this local planning note'
      && draft.settings?.modelId === 'astra' && draft.settings?.mode === 'plan' && draft.settings?.effort === 'medium')
  })).toBe(true)
  await page.getByRole('button', { name: 'New conversation' }).click()
  await expect(page.getByRole('textbox', { name: 'Message' })).toHaveText('')
  await expect(page.getByRole('button', { name: 'Draft Keep this local planning note' })).toBeVisible()
  await page.getByRole('button', { name: 'Project review' }).click()
  await expect(page.locator('.chat-transcript')).toContainText('The project has a README.')
  await page.getByRole('button', { name: 'Draft Keep this local planning note' }).click()
  await expect(page.getByRole('textbox', { name: 'Message' })).toHaveText('Keep this local planning note')
  await expect(page.getByRole('combobox', { name: 'Model' })).toHaveValue('astra')
  await expect(page.getByRole('button', { name: 'Plan mode' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Chat options' }).click()
  await expect(page.getByRole('combobox', { name: 'Reasoning effort' })).toHaveValue('medium')
  await page.screenshot({ path: `${evidence}/draft-settings-1280x860.png` })

  await page.reload()
  await expect(page.getByRole('button', { name: 'Draft Keep this local planning note' })).toBeVisible()
  await page.getByRole('button', { name: 'Draft Keep this local planning note' }).click()
  await expect(page.getByRole('textbox', { name: 'Message' })).toHaveText('Keep this local planning note')
  await expect(page.getByRole('combobox', { name: 'Model' })).toHaveValue('astra')
  await page.setViewportSize({ width: 800, height: 600 })
  await expect(page.getByRole('textbox', { name: 'Message' })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `${evidence}/draft-settings-800x600.png` })
})

test('uses the real editor menus and paste previews without accidental sends', async ({ page }) => {
  const message = page.getByRole('textbox', { name: 'Message' })
  await page.getByRole('button', { name: 'Project review' }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__chatExperience.inspect().agentCalls?.includes('agents.list') ?? false)).toBe(true)
  await page.getByRole('button', { name: 'Chat options', exact: true }).click()
  await expect(page.getByRole('combobox', { name: 'Chat identity' })).toContainText('Release guide')
  await page.getByRole('button', { name: 'Chat options', exact: true }).click()
  await message.click()
  await page.keyboard.type('@Re')
  const mentions = page.getByRole('listbox', { name: 'Agents and references' })
  await expect(mentions).toBeVisible()
  await expect(mentions.getByRole('option', { name: /Release guide/ })).toBeVisible()
  await expect(mentions.getByRole('option', { name: /README.md/ })).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Enter')
  await expect(message).toContainText('@README.md')
  await page.keyboard.press('Meta+z')
  await expect(message).not.toContainText('@README.md')
  await page.keyboard.press('Meta+Shift+z')
  await expect(message).toContainText('@README.md')

  await message.click()
  await page.keyboard.press('End')
  await page.keyboard.type(' /')
  const commands = page.getByRole('listbox', { name: 'Plan and skills' })
  await expect(commands).toBeVisible()
  await expect(commands.getByRole('option', { name: /Plan mode/ })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(commands).toHaveCount(0)
  await page.keyboard.press('Shift+Enter')
  const sendsBefore = await page.evaluate(() => (window as any).__chatExperience.inspect().requests.filter((entry: any) => entry.method === 'foreground.submit').length)
  await message.evaluate(element => {
    element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true, isComposing: true }))
    element.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true, cancelable: true, repeat: true }))
  })
  await expect.poll(() => page.evaluate(() => (window as any).__chatExperience.inspect().requests.filter((entry: any) => entry.method === 'foreground.submit').length)).toBe(sendsBefore)
  await expect(message).toContainText('\n')

  await message.evaluate(async element => {
    const transfer = new DataTransfer()
    transfer.items.add(new File(['Readable project note'], 'brief.txt', { type: 'text/plain' }))
    const canvas = document.createElement('canvas')
    canvas.width = 180; canvas.height = 80
    const context = canvas.getContext('2d')!
    context.fillStyle = '#e66b54'; context.fillRect(0, 0, 90, 80)
    context.fillStyle = '#527c9b'; context.fillRect(90, 0, 90, 80)
    context.fillStyle = '#f4c56a'; context.fillRect(70, 20, 40, 40)
    const png = await new Promise<Blob>(resolve => canvas.toBlob(blob => resolve(blob!), 'image/png'))
    transfer.items.add(new File([png], 'pixel.png', { type: 'image/png' }))
    element.dispatchEvent(new ClipboardEvent('paste', { bubbles: true, cancelable: true, clipboardData: transfer }))
  })
  const attached = page.getByRole('list', { name: 'Attached context' })
  await expect(attached.getByRole('button', { name: 'Preview brief.txt' })).toBeVisible()
  await expect(attached.getByRole('button', { name: 'Preview pixel.png' })).toBeVisible()
  await attached.getByRole('button', { name: 'Preview brief.txt' }).click()
  const textPreview = page.getByRole('dialog', { name: 'Preview brief.txt' })
  await expect(textPreview.locator('pre')).toHaveText('Readable project note')
  await textPreview.getByRole('button', { name: 'Close preview' }).click()
  await expect(attached.getByRole('button', { name: 'Preview brief.txt' })).toBeFocused()
  await attached.getByRole('button', { name: 'Preview pixel.png' }).click()
  await expect(page.getByRole('dialog', { name: 'Preview pixel.png' }).locator('img')).toHaveAttribute('src', /^data:image\/png;base64,/)

  await page.setViewportSize({ width: 1280, height: 860 })
  await page.screenshot({ path: `${evidence}/attachments-preview-1280x860.png` })
  await page.setViewportSize({ width: 800, height: 600 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `${evidence}/attachments-preview-800x600.png` })
})

test('queues Enter, steers with Cmd+Enter, supports queue edits and Stop, and groups transcript work', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 860 })
  await page.getByRole('button', { name: 'Active work' }).click()
  const transcript = page.locator('.chat-transcript')
  await expect(transcript.locator('.chat-work-summary')).toContainText('Completed work')
  await expect(transcript.locator('.chat-work-summary')).toContainText('1 reasoning')
  await expect(page.getByRole('navigation', { name: 'Conversation turns' })).toBeVisible()
  await transcript.evaluate(element => { element.scrollTop = 0; element.dispatchEvent(new Event('scroll', { bubbles: true })) })
  await expect(page.getByRole('button', { name: 'Jump to latest' })).toBeVisible()
  await page.evaluate(() => (window as any).__chatExperience.emit('item/agentMessage/delta', { threadId: 'chat-running', turnId: 'turn-live', itemId: 'agent-live', delta: ' New streamed detail.' }))
  await expect(transcript).toContainText('New streamed detail.')
  await expect(page.getByRole('button', { name: 'Jump to latest' })).toBeVisible()

  const editor = page.getByRole('textbox', { name: 'Message' })
  const queue = page.getByRole('region', { name: 'Message queue' })
  await expect(queue).toHaveCount(0)
  await editor.fill('Queue this message')
  await page.keyboard.press('Enter')
  await expect(queue).toContainText('Queue this message')
  await queue.locator('summary').filter({ hasText: 'Queue this message' }).click()
  await queue.getByRole('button', { name: 'Edit' }).click()
  await queue.getByRole('textbox', { name: 'Edit queued message' }).fill('Edited queued instruction')
  await queue.getByRole('button', { name: 'Save edit' }).click()
  await expect(queue).toContainText('Edited queued instruction')
  await queue.getByRole('button', { name: 'Pause queue' }).click()
  await expect(queue).toContainText('Queue paused')
  await queue.getByRole('button', { name: 'Resume queue' }).click({ force: true })
  await expect(queue).not.toContainText('Queue paused')
  await queue.getByRole('button', { name: 'Remove' }).click()
  await expect(queue).toHaveCount(0)
  await editor.fill('Use queue steer now')
  await page.keyboard.press('Enter')
  await queue.locator('summary').filter({ hasText: 'Use queue steer now' }).click()
  await queue.getByRole('button', { name: 'Steer now' }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__chatExperience.inspect().requests.some((entry: any) => entry.method === 'queue.steer'))).toBe(true)
  await expect(queue).toHaveCount(0)

  await editor.fill('Steer this active turn')
  await page.keyboard.press('Meta+Enter')
  await expect.poll(() => page.evaluate(() => (window as any).__chatExperience.inspect().requests.some((entry: any) => entry.method === 'foreground.submit' && entry.params.delivery === 'steer' && entry.params.document.text === 'Steer this active turn'))).toBe(true)
  await editor.fill('Keep this instruction queued')
  await page.keyboard.press('Enter')
  await expect(queue).toContainText('Keep this instruction queued')
  await expect(page.getByRole('button', { name: 'Stop' })).toBeVisible()
  await page.screenshot({ path: `${evidence}/running-queue-1280x860.png` })
  await page.getByRole('button', { name: 'Stop' }).click()
  await expect(page.getByRole('button', { name: 'Stop' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Previous turn' }).click()
  await expect(page.locator('.chat-transcript [data-turn-id="turn-old"]').first()).toBeInViewport()
  await page.getByRole('button', { name: 'New tab' }).click()
  await page.getByRole('tabpanel', { name: 'New tab' }).getByRole('button', { name: 'Files' }).click()
  await expect(page.getByRole('tabpanel', { name: 'Files' })).toBeVisible()
  const resizer = page.getByRole('separator', { name: 'Resize workspace panel' })
  const widthBefore = Number(await resizer.getAttribute('aria-valuenow'))
  await resizer.focus()
  await page.keyboard.press('ArrowLeft')
  await expect.poll(async () => Number(await resizer.getAttribute('aria-valuenow'))).toBeGreaterThan(widthBefore)

  await page.setViewportSize({ width: 800, height: 600 })
  await expect(queue).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: `${evidence}/running-queue-800x600.png` })
})
